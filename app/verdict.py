UNVERIFIED = "Unverified"

SUMMARIES = {
    TRUE: "Credible sources support this claim, and nothing strong says the date or the story is wrong.",
    FALSE: "Reporting contradicts this claim.",
    MISLEADING: "The claim does not match the date or the context of the evidence.",
    UNVERIFIED: "There is not enough from credible sources to call this claim true, false, or misleading.",
}


def host_of(url: str) -> str:
    host = urlparse(url).netloc.lower()
    if host.startswith("www."):
        host = host[4:]
    return host


def _matches(host: str, domains: tuple[str, ...]) -> bool:
    return any(host == domain or host.endswith("." + domain) for domain in domains)


def is_rumor(url: str) -> bool:
    return _matches(host_of(url), RUMOR)


def tier(url: str) -> int:
    """1 for wires and major outlets, 2 for established magazines and regional papers, else 0."""
    host = host_of(url)
    if _matches(host, RUMOR):
        return 0
    if _matches(host, TIER1):
        return 1
    if _matches(host, TIER2) or _matches(host, FACTCHECK):
        return 2
    return 0


def is_credible(url: str) -> bool:
    return tier(url) > 0


def _tone(text: str) -> str:
    lowered = (text or "").lower()
    if any(phrase in lowered for phrase in FAKE_PHRASES):
        return "fake"
    if any(phrase in lowered for phrase in OOC_PHRASES):
        return "ooc"
    return "neutral"


def _recent_claim(text: str) -> bool:
    lowered = (text or "").lower()
    return any(phrase in lowered for phrase in RECENCY)


def _parse_when(value: str) -> datetime | None:
    value = (value or "").strip()
    if not value:
        return None
    for fmt in ("%Y:%m:%d %H:%M:%S", "%Y-%m-%dT%H:%M:%S", "%Y-%m-%d"):
        try:
            return datetime.strptime(value[: len(datetime.now().strftime(fmt))], fmt)
        except ValueError:
            continue
    if len(value) >= 10 and value[4] == "-" and value[7] == "-":
        try:
            return datetime.strptime(value[:10], "%Y-%m-%d")
        except ValueError:
            return None
    return None


def _iso(value: datetime | None) -> str:
    if not value:
        return ""
    return value.strftime("%Y-%m-%dT%H:%M:%S")


def _clue(title: str, detail: str, weight: str, url: str = "", source: str = "") -> dict:
    return {
        "title": title,
        "detail": detail[:320],
        "weight": weight,
        "url": url,
        "source": source,
    }


def decide(
    claim: dict,
    credentials: dict,
    web: dict,
    reverse: dict,
    detector: dict,
    now: datetime | None = None,
    posted_at: str = "",
) -> dict:
    now = now or datetime.now(timezone.utc)
    text = claim.get("text") or ""
    exif = credentials.get("exif") or {}
    c2pa = credentials.get("c2pa") or {}
    real = fake = ooc = 0
    contributions: list[dict] = []

    def _add(bucket: str, points: int, title: str, detail: str, url: str = "") -> None:
        nonlocal real, fake, ooc
        if bucket == "real":
            real += points
        elif bucket == "fake":
            fake += points
        elif bucket == "out_of_context":
            ooc += points
        contributions.append(
            {
                "bucket": bucket,
                "points": points,
                "title": title,
                "detail": detail[:320],
                "url": url,
            }
        )

    if c2pa.get("generative") or credentials.get("software_generative"):
        tool = exif.get("software") or "a generative tool"
        _add(
            "weak",
            0,
            "Weak clue: generative file marker",
            f"The file names {tool}. That is a weak signal about the picture, not a verdict on the claim.",
        )
    elif c2pa.get("present") and c2pa.get("camera"):
        _add(
            "weak",
            0,
            "Weak clue: camera content credentials",
            "A C2PA manifest names a camera. That does not by itself prove the claim.",
        )

    captured = _parse_when(exif.get("datetime") or "")
    date_conflict = False
    strong_date_conflict = False
    if captured and _recent_claim(text):
        age_days = (now.date() - captured.date()).days
        if age_days > 30:
            _add(
                "out_of_context",
                40,
                "Capture date contradicts the claim",
                f"The file is dated {captured.strftime('%Y-%m-%d')}, but the claim describes something happening now.",
            )
            date_conflict = True
            strong_date_conflict = True
        elif age_days > 2:
            _add(
                "out_of_context",
                16,
                "Capture date looks stale",
                f"The file is dated {captured.strftime('%Y-%m-%d')}, which is older than the claim's timeframe.",
            )
            date_conflict = True

    posted = _parse_when(posted_at or "")
    if posted and _recent_claim(text):
        post_age = (now.date() - posted.date()).days
        if post_age > 30:
            _add(
                "out_of_context",
                40,
                "Post date contradicts the claim",
                f"The post is dated {posted.strftime('%Y-%m-%d')}, but the claim describes something happening now.",
            )
            date_conflict = True
            strong_date_conflict = True
        elif post_age > 2:
            _add(
                "out_of_context",
                16,
                "Post date looks stale",
                f"The post is dated {posted.strftime('%Y-%m-%d')}, which is older than the claim's timeframe.",
            )
            date_conflict = True

    hits = list((web.get("search") or {}).get("hits") or [])
    for page in (web.get("contents") or {}).get("pages") or []:
        if page.get("url") and page.get("excerpt"):
            for hit in hits:
                if hit["url"] == page["url"] and len(page["excerpt"]) > len(hit.get("excerpt") or ""):
                    hit["excerpt"] = page["excerpt"]
    for citation in (web.get("answer") or {}).get("citations") or []:
        if citation.get("url") and not any(hit["url"] == citation["url"] for hit in hits):
            hits.append(
                {
                    "url": citation["url"],
                    "title": citation.get("title") or host_of(citation["url"]),
                    "excerpt": citation.get("excerpt") or "",
                    "page_age": "",
                    "bucket": "citation",
                    "found_by": "You.com Answer",
                }
            )

    fake_hits = []
    ooc_hits = []
    support_hits = []
    for hit in hits:
        blob = f"{hit.get('title', '')} {hit.get('excerpt', '')}"
        tone = _tone(blob)
        if tone == "fake":
            fake_hits.append(hit)
        elif tone == "ooc":
            ooc_hits.append(hit)
        elif is_credible(hit["url"]):
            support_hits.append(hit)

    if fake_hits:
        pts = 28 + min(12, 6 * (len(fake_hits) - 1))
        hit = fake_hits[0]
        _add("fake", pts, "Coverage calls it false", hit.get("excerpt") or hit.get("title") or "A source describes the image as generated or false.", hit.get("url") or "")
    if ooc_hits:
        pts = 28 + min(12, 6 * (len(ooc_hits) - 1))
        hit = ooc_hits[0]
        _add("out_of_context", pts, "Coverage says it is miscaptioned", hit.get("excerpt") or hit.get("title") or "A source describes this as older or out of context.", hit.get("url") or "")
    # Generic topical news does not confirm that this specific image was taken
    # when the file's capture date already contradicts the claim's timeframe.
    if strong_date_conflict and support_hits:
        contributions.append(
            {
                "bucket": "real",
                "points": 0,
                "title": "Topical news not counted as confirmation",
                "detail": "Credible outlets are covering a similar topic, but that does not prove this file was taken when the claim says.",
                "url": support_hits[0].get("url") or "",
            }
        )
    elif not strong_date_conflict:
        if len(support_hits) >= 2:
            top = support_hits[0]
            _add("real", 40, "Multiple credible sources", f"{len(support_hits)} credible outlets report the claim. {top.get('title') or ''}", top.get("url") or "")
        elif len(support_hits) == 1:
            top = support_hits[0]
            _add("real", 18, "One credible source", top.get("title") or "A credible outlet reports the claim.", top.get("url") or "")

    answer_text = (web.get("answer") or {}).get("text") or ""
    answer_tone = _tone(answer_text)
    if answer_tone == "fake":
        _add("fake", 12, "Cited synthesis flags a fake", answer_text[:240])
    elif answer_tone == "ooc":
        _add("out_of_context", 12, "Cited synthesis flags a mismatch", answer_text[:240])
    elif (
        answer_text
        and "reporting" in answer_text.lower()
        and support_hits
        and not strong_date_conflict
    ):
        _add("real", 6, "Cited synthesis agrees", "The You.com answer says credible reporting supports the claim.")

    detector_score = float(detector.get("score") or 0)
    if detector_score >= 0.75:
        _add(
            "weak",
            0,
            "Weak clue: AI-image prior",
            f"Local prior score {detector_score:.2f}. Not a lab result, and not a verdict on the claim.",
        )

    for match in reverse.get("matches") or []:
        seen = _parse_when(match.get("date") or "")
        if seen and _recent_claim(text) and (now.date() - seen.date()).days > 30:
            _add("out_of_context", 20, "Reverse image first seen earlier", f"A similar image appears dated {seen.strftime('%Y-%m-%d')}.", match.get("url") or "")
            date_conflict = True
            break

    # A strong capture-date conflict beats generic corroboration, unless the
    # file itself is clearly generative (C2PA / software tag / high fake score).
    if strong_date_conflict and fake < 38:
        target = max(ooc, real + 16, fake + 16)
        extra = target - ooc
        if extra:
            _add(
                "out_of_context",
                extra,
                "Date conflict outweighs topical news",
                "An old file date plus a now-claim is not rescued by generic coverage of the same topic.",
            )

    scores = {"real": real, "fake": fake, "out_of_context": ooc}
    ranked = sorted(
        ((TRUE, real), (FALSE, fake), (MISLEADING, ooc)),
        key=lambda item: item[1],
        reverse=True,
    )
    top_label, top_score = ranked[0]
    second_score = ranked[1][1]
    contested = top_score >= 25 and (top_score - second_score) < 8
    if strong_date_conflict and fake < 38:
        verdict = MISLEADING
    elif top_score < 25 or contested:
        verdict = UNVERIFIED
    else:
        verdict = top_label

    source_count = len(support_hits)
    if verdict == "Unverified":
        confidence = int(max(22, min(46, 24 + top_score)))
    else:
        gap = max(0, top_score - second_score)
        confidence = 44 + min(28, top_score // 2) + min(10, gap // 4)
        if source_count >= 2 and verdict == TRUE:
            confidence += 6
        if source_count == 0 and verdict == TRUE:
            confidence -= 8
        confidence = int(max(38, min(90, confidence)))

    clues = _build_clues(
        claim,
        credentials,
        web,
        reverse,
        detector,
        date_conflict,
        strong_date_conflict,
        captured,
        support_hits,
        fake_hits,
        ooc_hits,
        contested,
    )
    sources = _sources(hits, reverse.get("matches") or [])
    timeline = _timeline(captured, hits, reverse.get("matches") or [], now)
    return {
        "verdict": verdict,
        "confidence": confidence,
        "summary": SUMMARIES[verdict],
        "scores": scores,
        "contributions": contributions,
        "clues": clues[:4],
        "sources": sources[:8],
        "timeline": timeline[:8],
    }


def _build_clues(
    claim,
    credentials,
    web,
    reverse,
    detector,
    date_conflict,
    strong_date_conflict,
    captured,
    support_hits,
    fake_hits,
    ooc_hits,
    contested,
) -> list[dict]:
    exif = credentials.get("exif") or {}
    c2pa = credentials.get("c2pa") or {}
    clues = []
    if c2pa.get("generative"):
        clues.append(
            _clue(
                "Weak clue: content credentials",
                "The file has a C2PA marker that names a generative tool. This does not decide the claim.",
                "weak",
                source="c2pa",
            )
        )
    elif credentials.get("software_generative"):
        clues.append(
            _clue(
                "Weak clue: file software tag",
                f"EXIF Software is {exif.get('software') or 'a generative tool'}. This does not decide the claim.",
                "weak",
                source="exif",
            )
        )
    elif exif.get("make"):
        when = exif.get("datetime") or "an unknown time"
        clues.append(
            _clue(
                "Camera metadata",
                f"{exif.get('make')} {exif.get('model')} recorded {when}.".replace("  ", " "),
                "supporting",
                source="exif",
            )
        )
    else:
        clues.append(
            _clue(
                "No camera metadata",
                "No EXIF camera make was found, and no C2PA manifest was detected.",
                "weak",
                source="exif",
            )
        )

    if date_conflict and captured:
        clues.append(
            _clue(
                "Capture time vs claim",
                f"The file date is {captured.strftime('%Y-%m-%d')}, while the claim describes something happening now.",
                "strong",
                source="timeline",
            )
        )
    elif ooc_hits:
        hit = ooc_hits[0]
        clues.append(
            _clue(
                "Earlier context",
                hit.get("excerpt") or hit.get("title") or "A source describes this as an older or miscaptioned image.",
                "strong",
                url=hit.get("url") or "",
                source="web",
            )
        )

    search_status = (web.get("search") or {}).get("status")
    if support_hits and strong_date_conflict:
        top = support_hits[0]
        clues.append(
            _clue(
                "News is topical, not this photo",
                "Credible outlets are covering a similar topic, but that does not confirm this file was taken when the claim says.",
                "supporting",
                url=top.get("url") or "",
                source="youcom",
            )
        )
    elif support_hits:
        top = support_hits[0]
        clues.append(
            _clue(
                "Reporting matches",
                f"{len(support_hits)} credible source{'s' if len(support_hits) != 1 else ''} match the claim. {top.get('title', '')}",
                "strong",
                url=top.get("url") or "",
                source="youcom",
            )
        )
    elif fake_hits:
        hit = fake_hits[0]
        clues.append(
            _clue(
                "Coverage calls it false",
                hit.get("excerpt") or hit.get("title") or "A source describes the image as generated or false.",
                "strong",
                url=hit.get("url") or "",
                source="youcom",
            )
        )
    elif search_status == "skipped":
        clues.append(
            _clue(
                "Live web not checked",
                (web.get("search") or {}).get("detail") or "You.com was not called.",
                "weak",
                source="youcom",
            )
        )
    elif search_status == "ok":
        clues.append(
            _clue(
                "No credible match",
                "You.com returned results, and none were a credible outlet plainly reporting this claim.",
                "supporting",
                source="youcom",
            )
        )
    elif search_status == "error":
        clues.append(
            _clue(
                "Live web failed",
                (web.get("search") or {}).get("detail") or "You.com search failed.",
                "weak",
                source="youcom",
            )
        )

    matches = reverse.get("matches") or []
    if matches and len(clues) < 4:
        clues.append(
            _clue(
                "Reverse image",
                f"A similar page showed up: {matches[0].get('title')}",
                "supporting",
                url=matches[0].get("url") or "",
                source="treg",
            )
        )

    if len(clues) < 4:
        clues.append(
            _clue(
                "Weak clue: AI-image prior",
                f"Score {float(detector.get('score') or 0):.2f}. {detector.get('note') or ''} It does not decide the claim.",
                "weak",
                source="detector",
            )
        )

    if contested and len(clues) < 4:
        clues.append(
            _clue(
                "Clues disagree",
                "The strongest signals are too close, so this stays unverified.",
                "supporting",
                source="verdict",
            )
        )

    if claim.get("text") and len(clues) < 3:
        clues.append(
            _clue("Claim under check", claim["text"], "supporting", source=claim.get("source") or "caption")
        )
    if len(clues) < 3:
        clues.append(
            _clue(
                "Still open",
                "A vision key, a You.com key, or a public image URL would add another receipt.",
                "weak",
                source="pipeline",
            )
        )
    return clues


def _sources(hits: list[dict], matches: list[dict]) -> list[dict]:
    rows = []
    seen = set()
    for hit in hits:
        url = hit.get("url") or ""
        if not url or url in seen:
            continue
        seen.add(url)
        rows.append(
            {
                "title": hit.get("title") or host_of(url),
                "url": url,
                "outlet": host_of(url),
                "excerpt": (hit.get("excerpt") or "")[:320],
                "page_age": hit.get("page_age") or "",
                "credible": is_credible(url) and host_of(url) not in FACTCHECK,
                "found_by": hit.get("found_by") or "You.com Search",
            }
        )
    for match in matches:
        url = match.get("url") or ""
        if not url or url in seen:
            continue
        seen.add(url)
        rows.append(
            {
                "title": match.get("title") or host_of(url),
                "url": url,
                "outlet": host_of(url),
                "excerpt": "Visual match from reverse image.",
                "page_age": match.get("date") or "",
                "credible": is_credible(url),
                "found_by": "Treg",
            }
        )
    return rows


def _timeline(captured, hits, matches, now: datetime) -> list[dict]:
    events = []
    if captured:
        events.append(
            {
                "at": _iso(captured),
                "label": "File timestamp (EXIF)",
                "url": "",
            }
        )
    for hit in hits:
        when = _parse_when(hit.get("page_age") or "")
        if when:
            events.append(
                {
                    "at": _iso(when),
                    "label": hit.get("title") or host_of(hit.get("url") or ""),
                    "url": hit.get("url") or "",
                }
            )
    for match in matches:
        when = _parse_when(match.get("date") or "")
        if when:
            events.append(
                {
                    "at": _iso(when),
                    "label": f"Treg first seen: {match.get('title') or 'match'}",
                    "url": match.get("url") or "",
                }
            )
    events.append({"at": now.strftime("%Y-%m-%dT%H:%M:%SZ"), "label": "Provenance check", "url": ""})
    events.sort(key=lambda item: item["at"])
    return events
