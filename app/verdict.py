"""Turn the clues into one verdict. The detector can move the score only a little."""

from __future__ import annotations

from datetime import datetime, timezone
from urllib.parse import urlparse

CREDIBLE = (
    "reuters.com",
    "apnews.com",
    "ap.org",
    "bbc.com",
    "bbc.co.uk",
    "nytimes.com",
    "washingtonpost.com",
    "theguardian.com",
    "npr.org",
    "bloomberg.com",
    "wsj.com",
    "aljazeera.com",
    "abcnews.go.com",
    "cbsnews.com",
    "nbcnews.com",
    "pbs.org",
    "politico.com",
    "axios.com",
    "france24.com",
    "dw.com",
    "theatlantic.com",
    "time.com",
    "ft.com",
    "cbc.ca",
)

FACTCHECK = (
    "snopes.com",
    "factcheck.org",
    "politifact.com",
    "fullfact.org",
    "leadstories.com",
)

FAKE_PHRASES = (
    "ai-generated",
    "ai generated",
    "artificially generated",
    "generated by ai",
    "not a real photo",
    "this image is fake",
    "fabricated",
    "deepfake",
    "digitally created",
    "midjourney",
    "stable diffusion",
    "no evidence this happened",
)

OOC_PHRASES = (
    "old photo",
    "old image",
    "miscaptioned",
    "miscaption",
    "out of context",
    "years ago",
    "originally published",
    "not from today",
    "recirculated",
    "archive photo",
    "unrelated photo",
    "taken in 20",
    "from 20",
)

RECENCY = (
    "today",
    "this morning",
    "tonight",
    "this afternoon",
    "this evening",
    "just now",
    "breaking",
    "an hour ago",
    "hours ago",
    "moments ago",
    "right now",
)

SUMMARIES = {
    "Likely Real": "Credible reporting lines up with the claim, and the file does not look synthetic.",
    "Likely AI or Fake": "The file or the coverage points to a generated or false image.",
    "Out of Context": "The picture may be real, but it does not match the time or the story in the claim.",
    "Unverified": "The clues do not agree enough to call this real, fake, or miscaptioned.",
}


def host_of(url: str) -> str:
    host = urlparse(url).netloc.lower()
    if host.startswith("www."):
        host = host[4:]
    return host


def is_credible(url: str) -> bool:
    host = host_of(url)
    return any(host == domain or host.endswith("." + domain) for domain in CREDIBLE + FACTCHECK)


def _tone(text: str) -> str:
    lowered = (text or "").lower()
    if any(phrase in lowered for phrase in FAKE_PHRASES):
        return "fake"
    if any(phrase in lowered for phrase in OOC_PHRASES):
        return "ooc"
    return "neutral"


def _recent_claim(text: str) -> bool:
    lowered = (text or "").lower()
    return any(phrase in lowered for phrase in RECENCY)


def _parse_when(value: str) -> datetime | None:
    value = (value or "").strip()
    if not value:
        return None
    for fmt in ("%Y:%m:%d %H:%M:%S", "%Y-%m-%dT%H:%M:%S", "%Y-%m-%d"):
        try:
            return datetime.strptime(value[: len(datetime.now().strftime(fmt))], fmt)
        except ValueError:
            continue
    if len(value) >= 10 and value[4] == "-" and value[7] == "-":
        try:
            return datetime.strptime(value[:10], "%Y-%m-%d")
        except ValueError:
            return None
    return None


def _iso(value: datetime | None) -> str:
    if not value:
        return ""
    return value.strftime("%Y-%m-%dT%H:%M:%S")


def _clue(title: str, detail: str, weight: str, url: str = "", source: str = "") -> dict:
    return {
        "title": title,
        "detail": detail[:320],
        "weight": weight,
        "url": url,
        "source": source,
    }


def decide(
    claim: dict,
    credentials: dict,
    web: dict,
    reverse: dict,
    detector: dict,
    now: datetime | None = None,
) -> dict:
    now = now or datetime.now(timezone.utc)
    text = claim.get("text") or ""
    exif = credentials.get("exif") or {}
    c2pa = credentials.get("c2pa") or {}
    real = fake = ooc = 0

    if c2pa.get("generative"):
        fake += 45
    elif credentials.get("software_generative"):
        fake += 38
    elif c2pa.get("present") and c2pa.get("camera"):
        real += 22

    if exif.get("make") and exif.get("model"):
        real += 8
    elif exif.get("make"):
        real += 5
    if exif.get("datetime"):
        real += 4

    captured = _parse_when(exif.get("datetime") or "")
    date_conflict = False
    if captured and _recent_claim(text):
        age_days = (now.date() - captured.date()).days
        if age_days > 30:
            ooc += 36
            date_conflict = True
        elif age_days > 2:
            ooc += 16
            date_conflict = True

    hits = list((web.get("search") or {}).get("hits") or [])
    for page in (web.get("contents") or {}).get("pages") or []:
        if page.get("url") and page.get("excerpt"):
            for hit in hits:
                if hit["url"] == page["url"] and len(page["excerpt"]) > len(hit.get("excerpt") or ""):
                    hit["excerpt"] = page["excerpt"]
    for citation in (web.get("answer") or {}).get("citations") or []:
        if citation.get("url") and not any(hit["url"] == citation["url"] for hit in hits):
            hits.append(
                {
                    "url": citation["url"],
                    "title": citation.get("title") or host_of(citation["url"]),
                    "excerpt": citation.get("excerpt") or "",
                    "page_age": "",
                    "bucket": "citation",
                }
            )

    fake_hits = []
    ooc_hits = []
    support_hits = []
    for hit in hits:
        blob = f"{hit.get('title', '')} {hit.get('excerpt', '')}"
        tone = _tone(blob)
        if tone == "fake":
            fake_hits.append(hit)
        elif tone == "ooc":
            ooc_hits.append(hit)
        elif is_credible(hit["url"]):
            support_hits.append(hit)

    if fake_hits:
        fake += 28 + min(12, 6 * (len(fake_hits) - 1))
    if ooc_hits:
        ooc += 28 + min(12, 6 * (len(ooc_hits) - 1))
    if len(support_hits) >= 2:
        real += 40
    elif len(support_hits) == 1:
        real += 18

    answer_text = (web.get("answer") or {}).get("text") or ""
    answer_tone = _tone(answer_text)
    if answer_tone == "fake":
        fake += 12
    elif answer_tone == "ooc":
        ooc += 12
    elif answer_text and "reporting" in answer_text.lower() and support_hits:
        real += 6

    detector_score = float(detector.get("score") or 0)
    if detector_score >= 0.75:
        fake += 12
    elif detector_score <= 0.25 and exif.get("make"):
        real += 4

    for match in reverse.get("matches") or []:
        seen = _parse_when(match.get("date") or "")
        if seen and _recent_claim(text) and (now.date() - seen.date()).days > 30:
            ooc += 20
            date_conflict = True
            break

    scores = {"real": real, "fake": fake, "out_of_context": ooc}
    ranked = sorted(
        (("Likely Real", real), ("Likely AI or Fake", fake), ("Out of Context", ooc)),
        key=lambda item: item[1],
        reverse=True,
    )
    top_label, top_score = ranked[0]
    second_score = ranked[1][1]
    contested = top_score >= 25 and (top_score - second_score) < 8
    if top_score < 25 or contested:
        verdict = "Unverified"
    else:
        verdict = top_label

    source_count = len(support_hits)
    if verdict == "Unverified":
        confidence = int(max(22, min(46, 24 + top_score)))
    else:
        gap = max(0, top_score - second_score)
        confidence = 44 + min(28, top_score // 2) + min(10, gap // 4)
        if source_count >= 2 and verdict == "Likely Real":
            confidence += 6
        if source_count == 0 and verdict == "Likely Real":
            confidence -= 8
        confidence = int(max(38, min(90, confidence)))

    clues = _build_clues(
        claim,
        credentials,
        web,
        reverse,
        detector,
        date_conflict,
        captured,
        support_hits,
        fake_hits,
        ooc_hits,
        contested,
    )
    sources = _sources(hits, reverse.get("matches") or [])
    timeline = _timeline(captured, hits, reverse.get("matches") or [], now)
    return {
        "verdict": verdict,
        "confidence": confidence,
        "summary": SUMMARIES[verdict],
        "scores": scores,
        "clues": clues[:4],
        "sources": sources[:8],
        "timeline": timeline[:8],
    }


def _build_clues(
    claim,
    credentials,
    web,
    reverse,
    detector,
    date_conflict,
    captured,
    support_hits,
    fake_hits,
    ooc_hits,
    contested,
) -> list[dict]:
    exif = credentials.get("exif") or {}
    c2pa = credentials.get("c2pa") or {}
    clues = []
    if c2pa.get("generative"):
        clues.append(
            _clue(
                "Content credentials",
                "The file has a C2PA marker that names a generative tool.",
                "strong",
                source="c2pa",
            )
        )
    elif credentials.get("software_generative"):
        clues.append(
            _clue(
                "File software tag",
                f"EXIF Software is {exif.get('software') or 'a generative tool'}.",
                "strong",
                source="exif",
            )
        )
    elif exif.get("make"):
        when = exif.get("datetime") or "an unknown time"
        clues.append(
            _clue(
                "Camera metadata",
                f"{exif.get('make')} {exif.get('model')} recorded {when}.".replace("  ", " "),
                "supporting",
                source="exif",
            )
        )
    else:
        clues.append(
            _clue(
                "No camera metadata",
                "No EXIF camera make was found, and no C2PA manifest was detected.",
                "weak",
                source="exif",
            )
        )

    if date_conflict and captured:
        clues.append(
            _clue(
                "Capture time vs claim",
                f"The file date is {captured.strftime('%Y-%m-%d')}, while the claim describes something happening now.",
                "strong",
                source="timeline",
            )
        )
    elif ooc_hits:
        hit = ooc_hits[0]
        clues.append(
            _clue(
                "Earlier context",
                hit.get("excerpt") or hit.get("title") or "A source describes this as an older or miscaptioned image.",
                "strong",
                url=hit.get("url") or "",
                source="web",
            )
        )

    search_status = (web.get("search") or {}).get("status")
    if support_hits:
        top = support_hits[0]
        clues.append(
            _clue(
                "Reporting matches",
                f"{len(support_hits)} credible source{'s' if len(support_hits) != 1 else ''} match the claim. {top.get('title', '')}",
                "strong",
                url=top.get("url") or "",
                source="youcom",
            )
        )
    elif fake_hits:
        hit = fake_hits[0]
        clues.append(
            _clue(
                "Coverage calls it false",
                hit.get("excerpt") or hit.get("title") or "A source describes the image as generated or false.",
                "strong",
                url=hit.get("url") or "",
                source="youcom",
            )
        )
    elif search_status == "skipped":
        clues.append(
            _clue(
                "Live web not checked",
                (web.get("search") or {}).get("detail") or "You.com was not called.",
                "weak",
                source="youcom",
            )
        )
    elif search_status == "ok":
        clues.append(
            _clue(
                "No credible match",
                "You.com returned results, and none were a credible outlet plainly reporting this claim.",
                "supporting",
                source="youcom",
            )
        )
    elif search_status == "error":
        clues.append(
            _clue(
                "Live web failed",
                (web.get("search") or {}).get("detail") or "You.com search failed.",
                "weak",
                source="youcom",
            )
        )

    matches = reverse.get("matches") or []
    if matches and len(clues) < 4:
        clues.append(
            _clue(
                "Reverse image",
                f"A similar page showed up: {matches[0].get('title')}",
                "supporting",
                url=matches[0].get("url") or "",
                source="treg",
            )
        )

    if len(clues) < 4:
        clues.append(
            _clue(
                "AI-image prior",
                f"Score {float(detector.get('score') or 0):.2f}. {detector.get('note') or ''}",
                "weak",
                source="detector",
            )
        )

    if contested and len(clues) < 4:
        clues.append(
            _clue(
                "Clues disagree",
                "The strongest signals are too close, so this stays unverified.",
                "supporting",
                source="verdict",
            )
        )

    if claim.get("text") and len(clues) < 3:
        clues.append(
            _clue("Claim under check", claim["text"], "supporting", source=claim.get("source") or "caption")
        )
    if len(clues) < 3:
        clues.append(
            _clue(
                "Still open",
                "A vision key, a You.com key, or a public image URL would add another receipt.",
                "weak",
                source="pipeline",
            )
        )
    return clues


def _sources(hits: list[dict], matches: list[dict]) -> list[dict]:
    rows = []
    seen = set()
    for hit in hits:
        url = hit.get("url") or ""
        if not url or url in seen:
            continue
        seen.add(url)
        rows.append(
            {
                "title": hit.get("title") or host_of(url),
                "url": url,
                "outlet": host_of(url),
                "excerpt": (hit.get("excerpt") or "")[:320],
                "page_age": hit.get("page_age") or "",
                "credible": is_credible(url) and host_of(url) not in FACTCHECK,
            }
        )
    for match in matches:
        url = match.get("url") or ""
        if not url or url in seen:
            continue
        seen.add(url)
        rows.append(
            {
                "title": match.get("title") or host_of(url),
                "url": url,
                "outlet": host_of(url),
                "excerpt": "Visual match from reverse image.",
                "page_age": match.get("date") or "",
                "credible": is_credible(url),
            }
        )
    return rows


def _timeline(captured, hits, matches, now: datetime) -> list[dict]:
    events = []
    if captured:
        events.append(
            {
                "at": _iso(captured),
                "label": "File timestamp (EXIF)",
                "url": "",
            }
        )
    for hit in hits:
        when = _parse_when(hit.get("page_age") or "")
        if when:
            events.append(
                {
                    "at": _iso(when),
                    "label": hit.get("title") or host_of(hit.get("url") or ""),
                    "url": hit.get("url") or "",
                }
            )
    for match in matches:
        when = _parse_when(match.get("date") or "")
        if when:
            events.append(
                {
                    "at": _iso(when),
                    "label": f"Similar image: {match.get('title') or 'match'}",
                    "url": match.get("url") or "",
                }
            )
    events.append({"at": now.strftime("%Y-%m-%dT%H:%M:%SZ"), "label": "Provenance check", "url": ""})
    events.sort(key=lambda item: item["at"])
    return events
